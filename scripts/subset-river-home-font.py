"""Build the homepage font subset from a minified Hugo homepage.

Usage: python scripts/subset-river-home-font.py public/index.html
Requires fonttools and brotli. Keeps static/fonts/river-sans.woff2 unchanged.
Missing/new characters covered by the original font use the remainder face;
characters absent from the original font retain the existing system fallback.
"""
import argparse
import re
from html.parser import HTMLParser
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


class HomeText(HTMLParser):
    def __init__(self):
        super().__init__()
        self.skip = 0
        self.parts = []

    def handle_starttag(self, tag, attrs):
        if tag in ("script", "style"):
            self.skip += 1

    def handle_endtag(self, tag):
        if tag in ("script", "style"):
            self.skip = max(0, self.skip - 1)

    def handle_data(self, data):
        if not self.skip:
            self.parts.append(data)


def unicode_ranges(codes):
    ranges = []
    start = end = None
    for code in sorted(codes):
        if end is not None and code == end + 1:
            end = code
        else:
            if start is not None:
                ranges.append(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}")
            start = end = code
    if start is not None:
        ranges.append(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}")
    return ",".join(ranges)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("html", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    home = HomeText()
    home.feed(args.html.read_text(encoding="utf-8-sig"))
    text = "".join(home.parts) + "".join(chr(code) for code in range(32, 127))
    for source in sorted((root / "assets/css").rglob("*.css")):
        text += "".join(re.findall(r"(?<![-\w])content:\s*['\"]([^'\"]*)", source.read_text(encoding="utf-8")))
    font = TTFont(root / "static/fonts/river-sans.woff2", recalcTimestamp=False)
    original_codes = set(font.getBestCmap())
    options = subset.Options()
    options.flavor = "woff2"
    options.recalc_timestamp = False
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(text=text)
    subsetter.subset(font)
    home_codes = set(font.getBestCmap())
    font.flavor = "woff2"
    output = root / "static/fonts/river-home.woff2"
    font.save(output)
    faces = []
    for family, filename, codes in (
        ("River Home", "river-home.woff2", home_codes),
        ("River Remainder", "river-sans.woff2", original_codes - home_codes),
    ):
        if codes:
            faces.append(f'''@font-face {{
  font-family: "{family}";
  src: url("/fonts/{filename}") format("woff2");
  font-style: normal;
  font-weight: 100 900;
  font-display: swap;
  unicode-range: {unicode_ranges(codes)};
}}''')
    css = "/* Generated by scripts/subset-river-home-font.py. Keep the full font as a fallback. */\n"
    css += "\n".join(faces)
    css += '''
body.river-home {
  --river-font: "PingFang TC", "River Home", "River Remainder", "Noto Sans TC", "Source Han Sans TC", "Microsoft JhengHei", sans-serif;
}
body.river-home .publication-header { font-family: "PingFang TC", "River Home", "River Remainder", "Noto Sans TC", "Microsoft JhengHei", sans-serif; }
'''
    (root / "assets/css/river-home-font.css").write_text(css, encoding="utf-8")
    print(f"Homepage font: {output.stat().st_size:,} bytes; {len(home_codes)} glyphs; {len(original_codes - home_codes)} fallback glyphs")


if __name__ == "__main__":
    main()
