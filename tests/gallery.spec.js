import { test, expect } from '@playwright/test';
for (const width of [390,1440]) for (const theme of ['light','dark']) {
 test(`gallery autoplay and reader controls at ${width}px ${theme}`,async({page})=>{
  await page.clock.install();
  await page.setViewportSize({width,height:900});
  await page.addInitScript(t=>localStorage.setItem('pref-theme',t),theme);
  await page.goto('/');
  const gallery=page.locator('.home-gallery-section');
  const current=()=>gallery.locator('[aria-current="true"]').getAttribute('data-gallery-dot');
  await expect(gallery).toHaveAttribute('data-gallery-playing','false');
  await page.clock.runFor(12000);
  expect(await current()).toBe('0');
  await gallery.scrollIntoViewIfNeeded();
  await page.mouse.move(0,0);
  await expect(gallery).toHaveAttribute('data-gallery-playing','true');
  await expect.poll(()=>gallery.locator('.home-gallery-slide').first().locator('img').evaluate(e=>e.complete&&e.naturalWidth>0)).toBe(true);
  expect(await gallery.locator('.home-gallery-slide img').first().evaluate(e=>e.currentSrc)).toMatch(/\.webp$/);
  const imageFit = await gallery.locator('.home-gallery-slide img').first().evaluate(image => {
    const frame = image.closest('.home-gallery-slide').getBoundingClientRect();
    const box = image.getBoundingClientRect();
    return { fit: getComputedStyle(image).objectFit, width: Math.abs(box.width - frame.width), height: Math.abs(box.height - frame.height) };
  });
  expect(imageFit.fit).toBe(width > 768 ? 'cover' : 'contain');
  expect(imageFit.width).toBeLessThan(1);
  expect(imageFit.height).toBeLessThan(1);
  await page.clock.runFor(2000);
  expect(await current()).toBe('0');
  await page.clock.runFor(1100);
  expect(await current()).toBe('1');
  await gallery.hover();
  await expect(gallery).toHaveAttribute('data-gallery-playing','false');
  await page.clock.runFor(12000);
  expect(await current()).toBe('1');
  await expect(gallery.locator('[data-gallery-toggle]')).toHaveCount(0);
  await page.mouse.move(0,0);
  await expect(gallery).toHaveAttribute('data-gallery-playing','true');
  await page.clock.runFor(3100);
  expect(await current()).toBe('2');
  await gallery.locator('[data-gallery-prev]').focus();
  await expect(gallery).toHaveAttribute('data-gallery-playing','false');
  await page.clock.runFor(12000);
  expect(await current()).toBe('2');
  await page.keyboard.press('ArrowRight');
  expect(await current()).toBe('3');
  await gallery.locator('[data-gallery-dot]').last().click();
  await gallery.locator('[data-gallery-next]').click();
  expect(await current()).toBe('0');
  await page.emulateMedia({reducedMotion:'reduce'});
  await expect(gallery).toHaveAttribute('data-gallery-playing','false');
  await page.clock.runFor(12000);
  expect(await current()).toBe('0');
  await gallery.locator('[data-gallery-next]').click();
  expect(await current()).toBe('1');
  expect(await gallery.locator('[data-gallery-track]').evaluate(e=>getComputedStyle(e).transitionDuration)).toBe('0s');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
  await gallery.screenshot({path:`.tmp/gallery-${width}-${theme}.png`});
 });
}
